#!/usr/bin/env node
'use strict';
/*
 * Generate words.js: the 50,000 most common English words that have a CMU
 * pronunciation, each with its stress-free ARPAbet pronunciation(s).
 *
 *   node tools/build_words.js --download   (fetch the two sources into tools/data/, then build)
 *   node tools/build_words.js              (build from the files already in tools/data/)
 *
 * Inputs
 *   tools/data/cmudict.dict   CMU Pronouncing Dictionary (cmusphinx/cmudict)
 *   tools/data/count_1w.txt   Peter Norvig's word counts (norvig.com/ngrams)
 *
 * Words are ranked by Norvig count. Words with no CMU pronunciation are skipped
 * *before* counting to 50,000, so the list is the 50,000 most common words that
 * can actually be matched to sounds. Single letters other than "a" and "i" are
 * dropped (the web counts are full of them and they would shadow real words
 * with the same sound, e.g. "b" and "be"). Contractions are kept when Norvig's
 * apostrophe-free spelling has a count and no ordinary word shares it
 * ("dont" -> "don't", but "its" stays "its").
 *
 * Output format (see words.js header): one word per line, best-ranked first,
 *   word|pron|pron...   where each pron is one character per phoneme, taken
 *   from the `symbols` list by index into SYMBOL_CHARS.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(__dirname, 'data');
const LIMIT = 50000;
const SOURCES = [
  ['cmudict.dict', 'https://raw.githubusercontent.com/cmusphinx/cmudict/master/cmudict.dict'],
  ['count_1w.txt', 'https://norvig.com/ngrams/count_1w.txt']
];
// One printable character per phoneme (39 ARPAbet symbols).
const SYMBOL_CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklm';

async function download() {
  fs.mkdirSync(DATA, { recursive: true });
  for (const [file, url] of SOURCES) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(url + ' -> HTTP ' + res.status);
    fs.writeFileSync(path.join(DATA, file), Buffer.from(await res.arrayBuffer()));
    console.log('downloaded', file);
  }
}

function readCmu() {
  const text = fs.readFileSync(path.join(DATA, 'cmudict.dict'), 'utf8');
  const prons = new Map();   // word -> [[symbol...], ...]
  for (const raw of text.split('\n')) {
    const line = raw.replace(/#.*/, '').trim();
    if (!line) continue;
    const parts = line.split(/\s+/);
    const word = parts[0].replace(/\(\d+\)$/, '');
    const phones = parts.slice(1).map((p) => p.replace(/\d/g, ''));
    if (!prons.has(word)) prons.set(word, []);
    prons.get(word).push(phones);
  }
  return prons;
}

function readCounts() {
  const text = fs.readFileSync(path.join(DATA, 'count_1w.txt'), 'utf8');
  const out = [];
  for (const line of text.split('\n')) {
    const tab = line.indexOf('\t');
    if (tab < 0) continue;
    out.push([line.slice(0, tab), Number(line.slice(tab + 1))]);
  }
  out.sort((a, b) => b[1] - a[1]);
  return out;
}

function build() {
  const cmu = readCmu();
  const counts = readCounts();

  // Contractions whose apostrophe-free spelling is not itself a CMU word.
  const contractions = new Map();
  for (const word of cmu.keys()) {
    if (!word.includes("'")) continue;
    const key = word.replace(/'/g, '');
    if (/^[a-z]+$/.test(key) && !cmu.has(key)) contractions.set(key, word);
  }

  const symbolSet = new Set();
  for (const variants of cmu.values()) for (const p of variants) for (const s of p) symbolSet.add(s);
  const symbols = [...symbolSet].sort();
  if (symbols.length !== SYMBOL_CHARS.length) {
    throw new Error('expected ' + SYMBOL_CHARS.length + ' phonemes, found ' + symbols.length + ': ' + symbols);
  }
  const charOf = new Map(symbols.map((s, i) => [s, SYMBOL_CHARS[i]]));

  const lines = [];
  for (const [key] of counts) {
    if (lines.length >= LIMIT) break;
    if (key.length === 1 && key !== 'a' && key !== 'i') continue;
    const word = cmu.has(key) ? key : contractions.get(key);
    if (!word) continue;
    const seen = new Set();
    for (const p of cmu.get(word)) seen.add(p.map((s) => charOf.get(s)).join(''));
    lines.push(word + '|' + [...seen].join('|'));
  }
  return { symbols, lines };
}

function render({ symbols, lines }) {
  return [
    '/*',
    ' * GENERATED by tools/build_words.js - do not edit by hand.',
    ' *',
    ' * The ' + lines.length + ' most common English words that have a CMU pronunciation,',
    ' * most frequent first (Norvig counts; see the script for the exact rules).',
    ' * `entries` is one word per line: word|pron|pron..., a pron being one character',
    ' * per ARPAbet phoneme (stress removed): the character at index i of `chars`',
    ' * stands for symbols[i].',
    ' *',
    ' * Pronunciations: CMU Pronouncing Dictionary (BSD-style licence, Carnegie Mellon).',
    ' * Frequencies: Peter Norvig, "Natural Language Corpus Data" (MIT licence).',
    ' */',
    '(function (root, factory) {',
    "  if (typeof module === 'object' && module.exports) module.exports = factory();",
    '  else root.TrunicWords = factory();',
    "})(typeof self !== 'undefined' ? self : this, function () {",
    "  'use strict';",
    '  return {',
    '    symbols: ' + JSON.stringify(symbols) + ',',
    '    chars: ' + JSON.stringify(SYMBOL_CHARS) + ',',
    '    entries: ' + JSON.stringify(lines.join('\n')),
    '  };',
    '});',
    ''
  ].join('\n');
}

(async () => {
  if (process.argv.includes('--download')) await download();
  const result = build();
  const out = path.join(ROOT, 'words.js');
  fs.writeFileSync(out, render(result));
  console.log('wrote', out, result.lines.length, 'words,', fs.statSync(out).size, 'bytes');
})().catch((e) => { console.error(e); process.exit(1); });
